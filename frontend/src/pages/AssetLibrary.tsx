import React, { useEffect, useState } from 'react';
import { useParams } from 'react-router-dom';
import {
  FolderOpen,
  Upload,
  Trash2,
  Image as ImageIcon,
  Film,
  Mic,
  Music,
  ExternalLink,
} from 'lucide-react';
import { assetService } from '../services/api';
import { GeneratedAsset } from '../types';
import { Button } from '../components/common/Button';
import { Card } from '../components/common/Card';
import { Badge } from '../components/common/Badge';

export const AssetLibrary: React.FC = () => {
  const { id } = useParams<{ id: string }>();
  const [projectId] = useState<string>(id || localStorage.getItem('activeProjectId') || '');
  const [assets, setAssets] = useState<GeneratedAsset[]>([]);
  const [filterType, setFilterType] = useState<string>('ALL');
  const [isUploading, setIsUploading] = useState(false);
  const [isLoading, setIsLoading] = useState(true);

  useEffect(() => {
    if (projectId) {
      loadAssets();
    }
  }, [projectId]);

  const loadAssets = async () => {
    try {
      setIsLoading(true);
      const data = await assetService.getAssets(projectId);
      setAssets(data);
    } catch (err) {
      console.error('Failed to load assets:', err);
    } finally {
      setIsLoading(false);
    }
  };

  const handleFileUpload = async (e: React.ChangeEvent<HTMLInputElement>) => {
    const file = e.target.files?.[0];
    if (!file || !projectId) return;

    setIsUploading(true);
    const formData = new FormData();
    formData.append('file', file);

    let type = 'IMAGE';
    if (file.type.startsWith('video/')) type = 'VIDEO';
    if (file.type.startsWith('audio/')) type = 'AUDIO';
    formData.append('type', type);

    try {
      await assetService.uploadAsset(projectId, formData);
      await loadAssets();
    } catch (err) {
      console.error('Failed to upload file:', err);
      alert('Upload failed. Ensure file is an image, audio, or video under 100MB.');
    } finally {
      setIsUploading(false);
      e.target.value = '';
    }
  };

  const handleDelete = async (assetId: string) => {
    try {
      await assetService.deleteAsset(assetId);
      setAssets((prev) => prev.filter((a) => a.id !== assetId));
    } catch (err) {
      console.error('Failed to delete asset:', err);
    }
  };

  const filteredAssets = filterType === 'ALL'
    ? assets
    : assets.filter((a) => a.type === filterType);

  return (
    <div className="space-y-6">
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 pb-4 border-b border-slate-800">
        <div>
          <div className="flex items-center gap-2 mb-1">
            <FolderOpen className="w-5 h-5 text-brand-400" />
            <h1 className="text-2xl font-bold text-white tracking-tight">Project Asset Library</h1>
          </div>
          <p className="text-xs text-slate-400">
            Browse AI generated media assets, voiceovers, background audio, or upload custom footage
          </p>
        </div>

        <div className="flex items-center gap-3">
          <label className="cursor-pointer inline-flex items-center justify-center font-medium rounded-lg text-sm px-4 py-2 gap-2 bg-brand-600 hover:bg-brand-500 text-white shadow-sm shadow-brand-500/20 transition-all">
            <input
              type="file"
              onChange={handleFileUpload}
              className="hidden"
              accept="image/*,video/*,audio/*"
            />
            <Upload className="w-3.5 h-3.5" />
            <span>{isUploading ? 'Uploading...' : 'Upload Custom Asset'}</span>
          </label>
        </div>
      </div>

      {/* Filter Tabs */}
      <div className="flex items-center gap-2 border-b border-slate-800 pb-3 overflow-x-auto">
        {['ALL', 'IMAGE', 'VIDEO', 'AUDIO', 'THUMBNAIL', 'MUSIC'].map((type) => (
          <button
            key={type}
            onClick={() => setFilterType(type)}
            className={`px-3 py-1.5 rounded-lg text-xs font-medium transition-colors ${
              filterType === type
                ? 'bg-brand-600 text-white shadow-sm'
                : 'text-slate-400 hover:text-white hover:bg-slate-800'
            }`}
          >
            {type}
          </button>
        ))}
      </div>

      {/* Assets Grid */}
      {isLoading ? (
        <div className="p-12 text-center text-slate-400">Loading asset gallery...</div>
      ) : filteredAssets.length === 0 ? (
        <div className="bg-slate-900 border border-slate-800 rounded-xl p-12 text-center space-y-3">
          <FolderOpen className="w-10 h-10 mx-auto text-slate-400" />
          <h4 className="font-semibold text-white">No assets found</h4>
          <p className="text-xs text-slate-400 max-w-sm mx-auto">
            Assets generated by the Image, Video, Voice, or Thumbnail agents will appear here. You can also upload your own files.
          </p>
        </div>
      ) : (
        <div className="grid grid-cols-2 md:grid-cols-3 lg:grid-cols-4 gap-4">
          {filteredAssets.map((asset) => (
            <Card key={asset.id} className="p-3 space-y-3 flex flex-col justify-between">
              <div>
                <div className="aspect-video bg-slate-950 rounded-lg overflow-hidden border border-slate-800 flex items-center justify-center relative">
                  {asset.type === 'IMAGE' || asset.type === 'THUMBNAIL' ? (
                    <img
                      src={asset.url}
                      alt={asset.prompt || 'Generated Asset'}
                      className="w-full h-full object-cover"
                    />
                  ) : asset.type === 'VIDEO' ? (
                    <video
                      src={asset.url}
                      controls
                      className="w-full h-full object-cover"
                    />
                  ) : (
                    <div className="p-4 text-center space-y-2">
                      <Mic className="w-8 h-8 mx-auto text-brand-400" />
                      <audio src={asset.url} controls className="w-full max-w-[140px]" />
                    </div>
                  )}
                </div>

                <div className="pt-2">
                  <div className="flex items-center justify-between text-[11px] mb-1">
                    <Badge variant="purple" size="sm">{asset.type}</Badge>
                    <span className="text-slate-400 font-mono text-[10px]">{asset.provider}</span>
                  </div>
                  <p className="text-xs text-slate-300 line-clamp-2" title={asset.prompt || ''}>
                    {asset.prompt || 'Manual Upload'}
                  </p>
                </div>
              </div>

              <div className="flex items-center justify-between pt-2 border-t border-slate-800/80 text-xs">
                <a
                  href={asset.url}
                  target="_blank"
                  rel="noreferrer"
                  className="text-brand-400 hover:underline flex items-center gap-1"
                >
                  <ExternalLink className="w-3 h-3" />
                  <span>Open</span>
                </a>

                <button
                  onClick={() => handleDelete(asset.id)}
                  className="text-slate-400 hover:text-rose-400 p-1 rounded transition-colors"
                  title="Delete Asset"
                >
                  <Trash2 className="w-3.5 h-3.5" />
                </button>
              </div>
            </Card>
          ))}
        </div>
      )}
    </div>
  );
};
